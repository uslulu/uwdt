package backend

import (
	"testing"

	"pwdtt/backend"
)

// Последовательность реальных строк лога подключения → этапы для экрана
func TestStageSequence(t *testing.T) {
	logs := []string{
		"[ГРУППА #1] Запрос кредов (хеш: r3CqEXgi...)",
		"[STREAM 100] [VKCalls] step1 OK, anonymous_token (290 chars)",
		"[ГРУППА #1] Креды OK, TURN: [90.156.234.241:19302], 9 воркеров",
		"[ГРУППА #2] Запрос кредов (хеш: D-R6G6vG...)", // вторая группа — назад не откатываемся
		"[СЕССИЯ #1] Relay: 90.156.234.241:51932",
		"[ДИСП] Воркер #1 зарегистрирован (всего: 1)",
		"Запрос прав администратора для настройки туннеля…",
		"[ДИСП] Воркер #2 зарегистрирован (всего: 2)",
		"Туннель utun7 поднят, маршруты: [0.0.0.0/1 128.0.0.0/1]",
		"[STREAM 200] [КАПЧА] AUTO: старт цепочки", // капча второй группы после подъёма — не показываем
	}
	got := backend.StageSequence(logs)
	want := []string{
		"Получаю доступ к звонку ВК…",
		"Доступ получен, подключаюсь к серверам ВК…",
		"Соединяюсь с серверами ВК…",
		"Поднято каналов: 1",
		"Подтвердите пароль администратора…",
		"Поднимаю туннель…",
	}
	if len(got) != len(want) {
		t.Fatalf("got %q", got)
	}
	for i := range want {
		if got[i] != want[i] {
			t.Errorf("#%d: got %q want %q", i, got[i], want[i])
		}
	}
}
